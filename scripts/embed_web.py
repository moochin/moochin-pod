# PlatformIO pre-build step: gzip data/index.html into a C header so the phone
# page is served straight from flash (no filesystem image to install, and a
# firmware update always updates the page too).
Import("env")  # noqa: F821  (provided by PlatformIO)

import gzip
import os

root = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(root, "data", "index.html")
out = os.path.join(root, "src", "web", "index_html_gz.h")

with open(src, "rb") as f:
    raw = f.read()
gz = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: reproducible

lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in gz[i : i + 20]) + ",")
header = (
    "// GENERATED by scripts/embed_web.py from data/index.html. Do not edit.\n"
    "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"
    "static const uint8_t kIndexHtmlGz[] = {\n" + "\n".join(lines) + "\n};\n"
    "static const size_t kIndexHtmlGzLen = %d;  // %d bytes before gzip\n" % (len(gz), len(raw))
)
old = open(out).read() if os.path.exists(out) else ""
if old != header:  # don't touch the file (and force a rebuild) when unchanged
    with open(out, "w") as f:
        f.write(header)
print("Embedded phone page: %d bytes -> %d gzipped" % (len(raw), len(gz)))
